/**
 * CSV helpers shared by the outreach scripts.
 *
 * Plain JS on purpose: the scripts run under Node's TypeScript stripping,
 * which needs real file extensions in imports, and tsconfig does not allow
 * importing ".ts" paths. A ".mjs" import satisfies both.
 */

/**
 * RFC 4180 parser: quoted fields, escaped quotes, commas and newlines inside
 * quotes, CRLF, a leading BOM. Blank lines are dropped.
 * @param {string} text
 * @returns {string[][]}
 */
export function parseCsv(text) {
  /** @type {string[][]} */
  const rows = [];
  /** @type {string[]} */
  let row = [];
  let field = "";
  let quoted = false;
  const src = text.replace(/^﻿/, "");

  for (let i = 0; i < src.length; i++) {
    const ch = src[i];
    if (quoted) {
      if (ch === '"') {
        if (src[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          quoted = false;
        }
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      quoted = true;
    } else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && src[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += ch;
    }
  }
  if (field !== "" || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.some((cell) => cell.trim() !== ""));
}

/**
 * Rows keyed by lower-cased, trimmed header; values trimmed.
 * @param {string} text
 * @returns {Record<string, string>[]}
 */
export function csvRecords(text) {
  const [header, ...rows] = parseCsv(text);
  if (!header) return [];
  const keys = header.map((h) => h.trim().toLowerCase());
  return rows.map((r) => Object.fromEntries(keys.map((k, i) => [k, (r[i] ?? "").trim()])));
}
